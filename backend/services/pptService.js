/**
 * Reuse the splitLong logic from ppt.js — splits long text into chunks.
 */
function splitLong(text, max = 650) {
  if (text.length <= max) return [text];
  const slides = [];
  let curr = '';
  for (const w of text.split(' ')) {
    if ((curr + w).length > max) {
      slides.push(curr.trim());
      curr = '';
    }
    curr += w + ' ';
  }
  if (curr.trim()) slides.push(curr.trim());
  return slides;
}

const MAX_BULLETS_PER_SLIDE = 6;
const MAX_LINES_PER_SLIDE = 8;

/**
 * Split bullet array into chunks that fit on one slide.
 */
function splitBullets(bullets) {
  if (!bullets || bullets.length <= MAX_BULLETS_PER_SLIDE) return [bullets || []];
  const chunks = [];
  for (let i = 0; i < bullets.length; i += MAX_BULLETS_PER_SLIDE) {
    chunks.push(bullets.slice(i, i + MAX_BULLETS_PER_SLIDE));
  }
  return chunks;
}

/**
 * Generate professional PPTX from structured AI content.
 *
 * @param {Object} structuredContent - { title, slides: [{title, bullets, notes, diagramSuggestion}] }
 * @param {Object} settings - { theme, slideCount }
 * @returns {Promise<Buffer>} PPTX file buffer
 */
export async function generatePPTX(structuredContent, settings = {}) {
  const themeName = settings.theme && THEMES[settings.theme] ? settings.theme : 'corporate';
  const theme = THEMES[themeName];
  const { title: presTitle, slides: contentSlides = [] } = structuredContent;

  const pptx = new PptxGenJS();
  pptx.author = 'DocuGenius AI';
  pptx.title = presTitle || 'Untitled Presentation';
  pptx.subject = presTitle || '';

  // ── Title Slide ──
  const titleSlide = pptx.addSlide();
  titleSlide.background = { color: theme.titleBg };
  titleSlide.addText(presTitle || 'Untitled Presentation', {
    x: 0.5, y: 1.5, w: 9, h: 1.5,
    fontSize: 40, bold: true, align: 'center',
    color: theme.titleColor, fontFace: theme.headingFont
  });
  titleSlide.addText(new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }), {
    x: 0.5, y: 3.5, w: 9, h: 0.6,
    fontSize: 16, align: 'center',
    color: theme.accent, fontFace: theme.bodyFont
  });
  titleSlide.addText('Generated by DocuGenius AI', {
    x: 0.5, y: 4.2, w: 9, h: 0.5,
    fontSize: 12, align: 'center', italic: true,
    color: theme.secondary, fontFace: theme.bodyFont
  });

  // ── Content Slides ──
  for (let i = 0; i < contentSlides.length; i++) {
    const slideData = contentSlides[i];
    const isLast = i === contentSlides.length - 1;

    // Section divider for the first slide and mid-point
    if (i === 0 || (contentSlides.length > 8 && i === Math.floor(contentSlides.length / 2))) {
      const divider = pptx.addSlide();
      divider.background = { color: theme.accent };
      const sectionLabel = i === 0 ? 'Overview' : 'Continued';
      divider.addText(sectionLabel, {
        x: 0.5, y: 2, w: 9, h: 2,
        fontSize: 36, bold: true, align: 'center',
        color: 'FFFFFF', fontFace: theme.headingFont
      });
    }

    // Handle diagram slides
    if (slideData.diagramSuggestion) {
      await addDiagramSlide(pptx, slideData, theme);
    }

    // Handle content overflow: split bullets across multiple slides
    const bulletChunks = splitBullets(slideData.bullets);

    for (let chunkIdx = 0; chunkIdx < bulletChunks.length; chunkIdx++) {
      const slide = pptx.addSlide();
      slide.background = { color: theme.background };

      // Slide title
      const slideTitle = chunkIdx > 0
        ? `${slideData.title || 'Content'} (continued)`
        : (slideData.title || 'Content');

      slide.addText(slideTitle, {
        x: 0.5, y: 0.3, w: 9, h: 0.7,
        fontSize: 28, bold: true, color: theme.headingColor || theme.primary,
        fontFace: theme.headingFont
      });

      // Accent underline
      slide.addShape(pptx.ShapeType.rect, {
        x: 0.5, y: 1.0, w: 2, h: 0.04,
        fill: { color: theme.accent }
      });

      // Bullets
      const bullets = bulletChunks[chunkIdx];
      if (bullets && bullets.length > 0) {
        const textRows = bullets.map(b => {
          // Handle long bullets by splitting
          const parts = splitLong(b, 120);
          return parts.map((part, pi) => ({
            text: pi === 0 ? `•  ${part}` : `   ${part}`,
            options: {
              fontSize: 18, color: theme.bodyColor || '333333',
              fontFace: theme.bodyFont, breakType: pi > 0 ? 'n' : undefined,
              lineSpacingMultiple: 1.3, paraSpaceAfter: 6
            }
          }));
        }).flat();

        slide.addText(textRows, {
          x: 0.5, y: 1.2, w: 9, h: 5.3,
          valign: 'top'
        });
      }

      // Speaker notes
      if (slideData.notes && chunkIdx === 0) {
        slide.addNotes(slideData.notes);
      }
    }
  }

  // ── Conclusion Slide ──
  const conclusionSlide = pptx.addSlide();
  conclusionSlide.background = { color: theme.titleBg };
  conclusionSlide.addText('Thank You', {
    x: 0.5, y: 1.5, w: 9, h: 1.5,
    fontSize: 44, bold: true, align: 'center',
    color: theme.titleColor, fontFace: theme.headingFont
  });
  conclusionSlide.addText('Questions & Discussion', {
    x: 0.5, y: 3.2, w: 9, h: 0.8,
    fontSize: 20, align: 'center',
    color: theme.accent, fontFace: theme.bodyFont
  });

  // Write to buffer
  const data = await pptx.write({ outputType: 'nodebuffer' });
  return Buffer.from(data);
}

/**
 * Add a diagram slide, either as an image or text fallback.
 */
async function addDiagramSlide(pptx, slideData, theme) {
  const slide = pptx.addSlide();
  slide.background = { color: theme.background };

  slide.addText(slideData.title ? `${slideData.title} – Diagram` : 'Diagram', {
    x: 0.5, y: 0.3, w: 9, h: 0.7,
    fontSize: 24, bold: true, color: theme.primary,
    fontFace: theme.headingFont
  });

  try {
    const imgBuffer = await generateDiagramImage(slideData.diagramSuggestion);
    if (imgBuffer) {
      // Check if it's SVG (text) or PNG (binary)
      const isSvg = imgBuffer.toString('utf-8', 0, 5).includes('<svg');
      if (isSvg) {
        // PptxGenJS doesn't natively support SVG, show as text fallback
        const textFallback = getDiagramTextFallback(slideData.diagramSuggestion);
        if (textFallback) {
          slide.addText(textFallback, {
            x: 0.5, y: 1.2, w: 9, h: 5.3,
            fontSize: 14, fontFace: 'Consolas', color: '333333',
            lineSpacingMultiple: 1.4, valign: 'top'
          });
        }
      } else {
        // PNG buffer — embed as image
        const base64 = imgBuffer.toString('base64');
        slide.addImage({
          data: `image/png;base64,${base64}`,
          x: 0.8, y: 1.3, w: 8.4, h: 5.0
        });
      }
    } else {
      // Text fallback
      const textFallback = getDiagramTextFallback(slideData.diagramSuggestion);
      if (textFallback) {
        slide.addText(textFallback, {
          x: 0.5, y: 1.2, w: 9, h: 5.3,
          fontSize: 14, fontFace: 'Consolas', color: '333333',
          lineSpacingMultiple: 1.4, valign: 'top'
        });
      }
    }
  } catch {
    // Silent fail — diagram is optional enhancement
    const textFallback = getDiagramTextFallback(slideData.diagramSuggestion);
    if (textFallback) {
      slide.addText(textFallback, {
        x: 0.5, y: 1.2, w: 9, h: 5.3,
        fontSize: 14, fontFace: 'Consolas', color: '333333',
        lineSpacingMultiple: 1.4, valign: 'top'
      });
    }
  }
}
