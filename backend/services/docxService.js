import {
  Document, Packer, Paragraph, TextRun, HeadingLevel,
  AlignmentType, PageBreak, Header, Footer,
  PageNumber, Table, TableRow, TableCell, WidthType,
  BorderStyle, ImageRun, NumberFormat
} from 'docx';
import { generateDiagramImage } from './diagramService.js';

/**
 * Generate professional DOCX from structured AI content.
 *
 * @param {Object} structuredContent - { title, sections: [{heading, level, content, bullets, tableData, diagramSuggestion}] }
 * @param {Object} settings - { author, theme }
 * @returns {Promise<Buffer>} DOCX file buffer
 */
export async function generateDOCX(structuredContent, settings = {}) {
  const { title = 'Untitled Document', sections = [] } = structuredContent;
  const author = settings.author || 'DocuGenius AI';
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });

  const children = [];

  // ── Title Page ──
  children.push(
    new Paragraph({ spacing: { before: 4000 } }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({ text: title, bold: true, size: 56, font: 'Calibri', color: '1a3a5c' })
      ],
      spacing: { after: 400 }
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({ text: dateStr, size: 24, font: 'Calibri', color: '666666' })
      ],
      spacing: { after: 200 }
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({ text: `By ${author}`, size: 22, font: 'Calibri', italics: true, color: '888888' })
      ],
      spacing: { after: 200 }
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({ text: 'Generated by DocuGenius AI', size: 18, font: 'Calibri', color: 'AAAAAA' })
      ]
    }),
    new Paragraph({ children: [new PageBreak()] })
  );

  // ── Table of Contents Placeholder ──
  children.push(
    new Paragraph({
      heading: HeadingLevel.HEADING_1,
      children: [new TextRun({ text: 'Table of Contents', bold: true })],
      spacing: { after: 400 }
    })
  );

  // Build TOC entries from sections
  for (const section of sections) {
    if (section.heading) {
      const indent = section.level === 2 ? 720 : section.level === 3 ? 1440 : 0;
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: section.heading,
              size: section.level === 1 ? 24 : 22,
              color: '3366cc',
              font: 'Calibri'
            })
          ],
          indent: { left: indent },
          spacing: { after: 80 }
        })
      );
    }
  }

  children.push(new Paragraph({ children: [new PageBreak()] }));

  // ── Sections ──
  for (let i = 0; i < sections.length; i++) {
    const section = sections[i];
    const headingLevel =
      section.level === 1 ? HeadingLevel.HEADING_1
      : section.level === 2 ? HeadingLevel.HEADING_2
      : section.level === 3 ? HeadingLevel.HEADING_3
      : HeadingLevel.HEADING_1;

    // Page break before major sections (level 1), except the first
    if (section.level === 1 && i > 0) {
      children.push(new Paragraph({ children: [new PageBreak()] }));
    }

    // Section heading
    if (section.heading) {
      children.push(
        new Paragraph({
          heading: headingLevel,
          children: [
            new TextRun({
              text: section.heading,
              bold: true,
              font: 'Calibri',
              color: '1a3a5c'
            })
          ],
          spacing: { before: 360, after: 200 }
        })
      );
    }

    // Content paragraphs
    if (section.content) {
      const paragraphs = section.content.split('\n').filter(Boolean);
      for (const para of paragraphs) {
        children.push(
          new Paragraph({
            children: [
              new TextRun({ text: para.trim(), size: 22, font: 'Calibri' })
            ],
            spacing: { after: 200 }
          })
        );
      }
    }

    // Bullet list
    if (section.bullets && Array.isArray(section.bullets) && section.bullets.length > 0) {
      for (const bullet of section.bullets) {
        children.push(
          new Paragraph({
            bullet: { level: 0 },
            children: [
              new TextRun({ text: bullet, size: 22, font: 'Calibri' })
            ],
            spacing: { after: 100 }
          })
        );
      }
      children.push(new Paragraph({ spacing: { after: 200 } }));
    }

    // Numbered list
    if (section.numberedItems && Array.isArray(section.numberedItems)) {
      section.numberedItems.forEach((item, idx) => {
        children.push(
          new Paragraph({
            children: [
              new TextRun({ text: `${idx + 1}. ${item}`, size: 22, font: 'Calibri' })
            ],
            indent: { left: 360 },
            spacing: { after: 100 }
          })
        );
      });
      children.push(new Paragraph({ spacing: { after: 200 } }));
    }

    // Table
    if (section.tableData && section.tableData.headers && section.tableData.rows) {
      const table = buildTable(section.tableData);
      children.push(table);
      children.push(new Paragraph({ spacing: { after: 300 } }));
    }

    // Diagram
    if (section.diagramSuggestion) {
      try {
        const imgBuffer = await generateDiagramImage(section.diagramSuggestion);
        if (imgBuffer && !imgBuffer.toString('utf-8', 0, 5).includes('<svg')) {
          children.push(
            new Paragraph({
              children: [
                new ImageRun({
                  data: imgBuffer,
                  transformation: { width: 550, height: 350 },
                  type: 'png'
                })
              ],
              alignment: AlignmentType.CENTER,
              spacing: { before: 200, after: 200 }
            })
          );
        } else {
          // Text fallback for diagram
          children.push(
            new Paragraph({
              children: [
                new TextRun({
                  text: `[Diagram: ${section.heading || 'Visual'}]`,
                  italics: true, size: 20, color: '888888', font: 'Calibri'
                })
              ],
              spacing: { after: 200 }
            })
          );
        }
      } catch {
        // Silently skip diagram on error
      }
    }
  }

  const doc = new Document({
    creator: author,
    title: title,
    description: `Generated by DocuGenius AI on ${dateStr}`,
    sections: [{
      properties: {
        page: {
          pageNumbers: { start: 1 }
        }
      },
      headers: {
        default: new Header({
          children: [
            new Paragraph({
              alignment: AlignmentType.RIGHT,
              children: [
                new TextRun({ text: title, italics: true, size: 18, color: '999999', font: 'Calibri' })
              ]
            })
          ]
        })
      },
      footers: {
        default: new Footer({
          children: [
            new Paragraph({
              alignment: AlignmentType.CENTER,
              children: [
                new TextRun({ text: 'Page ', size: 18, font: 'Calibri' }),
                new TextRun({ children: [PageNumber.CURRENT], size: 18, font: 'Calibri' }),
                new TextRun({ text: ' of ', size: 18, font: 'Calibri' }),
                new TextRun({ children: [PageNumber.TOTAL_PAGES], size: 18, font: 'Calibri' })
              ]
            })
          ]
        })
      },
      children
    }]
  });

  const buffer = await Packer.toBuffer(doc);
  return buffer;
}

/**
 * Build a docx Table from tableData.
 */
function buildTable(tableData) {
  const { headers, rows } = tableData;
  const borderStyle = {
    style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC'
  };
  const borders = {
    top: borderStyle, bottom: borderStyle,
    left: borderStyle, right: borderStyle
  };

  // Header row
  const headerRow = new TableRow({
    tableHeader: true,
    children: headers.map(h =>
      new TableCell({
        borders,
        width: { size: Math.floor(9000 / headers.length), type: WidthType.DXA },
        shading: { fill: '1a3a5c' },
        children: [
          new Paragraph({
            children: [
              new TextRun({ text: h, bold: true, color: 'FFFFFF', size: 20, font: 'Calibri' })
            ],
            alignment: AlignmentType.CENTER
          })
        ]
      })
    )
  });

  // Data rows
  const dataRows = rows.map((row, rowIdx) =>
    new TableRow({
      children: row.map(cell =>
        new TableCell({
          borders,
          width: { size: Math.floor(9000 / headers.length), type: WidthType.DXA },
          shading: rowIdx % 2 === 0 ? { fill: 'F8F8F8' } : undefined,
          children: [
            new Paragraph({
              children: [
                new TextRun({ text: String(cell), size: 20, font: 'Calibri' })
              ]
            })
          ]
        })
      )
    })
  );

  return new Table({
    rows: [headerRow, ...dataRows],
    width: { size: 9000, type: WidthType.DXA }
  });
}
